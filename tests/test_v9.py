from playwright.sync_api import sync_playwright
URL=__import__("fcenv").APP_URL
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch()
    c=b.new_context(viewport={"width":1360,"height":900},color_scheme="light")
    pg=c.new_page(); pg.on("pageerror",lambda e:errs.append(str(e))); pg.on("console",lambda m: errs.append(m.text) if m.type=="error" else None)
    pg.add_init_script("""window.__spoken=[]; window.SpeechSynthesisUtterance=function(t){this.text=t;window.__spoken.push(t)}; try{speechSynthesis.speak=function(u){setTimeout(()=>{u.onend&&u.onend()},10)}; speechSynthesis.cancel=function(){}}catch(e){}""")
    pg.goto(URL); pg.wait_for_timeout(600)
    print("recipes",pg.evaluate("RECIPES.length"),"mit cost",pg.evaluate("RECIPES.every(r=>typeof r.cost==='number')"),"PRICE",pg.evaluate("Object.keys(PRICE).length"))
    pg.evaluate("showTab('rezepte')"); pg.wait_for_timeout(300); pg.screenshot(path=__import__("fcenv").SHOTS + "/v9-rezepte.png")
    pg.select_option('#rsort','cost'); pg.wait_for_timeout(200)
    print("billigstes:",pg.inner_text('.rcard >> nth=0').replace("\n"," | "))
    pg.click('.rcard >> nth=3'); pg.wait_for_timeout(500); pg.screenshot(path=__import__("fcenv").SHOTS + "/v9-dialog.png")
    pg.click('[data-por="1"]'); pg.click('[data-cartadd]'); pg.wait_for_timeout(200)
    print("cart",pg.evaluate("JSON.stringify(CART)"))
    pg.evaluate("closeDialog(document.querySelector('#dlg-recipe'))"); pg.wait_for_timeout(400)
    pg.evaluate("showTab('rad')"); pg.click('[data-rmode="week"]'); pg.click('#spin'); pg.wait_for_timeout(500); pg.click('#skipspin'); pg.wait_for_timeout(1500)
    print("rad shop:", pg.inner_text('.radshop .rday-h').replace("\n"," "))
    pg.evaluate("document.querySelector('.radshop').scrollIntoView()"); pg.screenshot(path=__import__("fcenv").SHOTS + "/v9-rad-shop.png")
    pg.click('[data-cartplan]'); pg.wait_for_timeout(300)
    pg.evaluate("showTab('einkauf')"); pg.wait_for_timeout(400); pg.screenshot(path=__import__("fcenv").SHOTS + "/v9-einkauf.png",full_page=True)
    print("cart items",pg.evaluate("CART.length"),"total",pg.evaluate("shopCalc(CART).total.toFixed(2)"))
    pg.fill('#budget','40'); pg.dispatch_event('#budget','change'); pg.wait_for_timeout(300)
    print("budget text:", pg.inner_text('.budget').replace("\n"," ")[:160])
    pg.click('#panel-einkauf .sline >> nth=0'); pg.wait_for_timeout(100)
    print("chk",pg.evaluate("JSON.stringify(CHK)"))
    pg.evaluate("window.__spoken.length=0")
    pg.evaluate("say('Test außerhalb')"); pg.evaluate("openRecipe('hartgekochte-eier', true)"); pg.wait_for_timeout(300)
    print("gesprochen außerhalb:", pg.evaluate("__spoken.length"))
    pg.evaluate("closeDialog(document.querySelector('#dlg-recipe'))"); pg.wait_for_timeout(400)
    pg.evaluate("act('start')"); pg.wait_for_timeout(200)
    pg.evaluate("act('next')"); pg.wait_for_timeout(300)
    pg.evaluate("act('done')"); pg.wait_for_timeout(300)
    print("gesprochen im Training:", pg.evaluate("JSON.stringify(__spoken)"))
    pg.evaluate("act('stop')")
    c.close()
    c=b.new_context(viewport={"width":390,"height":844},color_scheme="dark",device_scale_factor=2)
    pg=c.new_page(); pg.on("pageerror",lambda e:errs.append(str(e)))
    pg.goto(URL); pg.wait_for_timeout(500)
    pg.evaluate("CART=[{id:'hartgekochte-eier',n:2},{id:'haehnchen-reis-pfanne',n:4},{id:'spaghetti-bolognese-mit-vollkornnudeln',n:2}]; renderShop()")
    pg.evaluate("showTab('einkauf')"); pg.wait_for_timeout(400); pg.screenshot(path=__import__("fcenv").SHOTS + "/v9-m-einkauf.png")
    print("overflow", pg.evaluate("document.documentElement.scrollWidth>innerWidth"))
    c.close(); b.close()
print("errors:",errs)
